from django.db import models
from django.conf import settings
from django.core.validators import MinValueValidator, MaxValueValidator
from django.utils import timezone
from decimal import Decimal

class Advisor(models.Model):
    user = models.OneToOneField(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='advisor_profile')
    name = models.CharField(max_length=255)
    slogan = models.CharField(max_length=255, blank=True)
    description = models.TextField(blank=True)
    rating = models.DecimalField(max_digits=3, decimal_places=2, default=0.00)
    experience = models.PositiveIntegerField(default=0)
    feedback_count = models.PositiveIntegerField(default=0)
    total_orders = models.PositiveIntegerField(default=0)
    is_verified = models.BooleanField(default=False)
    is_active = models.BooleanField(default=True)
    is_featured = models.BooleanField(default=False)
    is_online = models.BooleanField(default=False)
    last_active = models.DateTimeField(null=True, blank=True)
    profile_image = models.ImageField(upload_to='advisor_images/', null=True, blank=True)
    cover_image = models.ImageField(upload_to='advisor_covers/', null=True, blank=True)
    sort_order = models.PositiveIntegerField(default=0)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.name} ({self.user.email})"

    def save(self, *args, **kwargs):
        if not self.slogan:
            self.slogan = "Professional Advisor"
        super().save(*args, **kwargs)

class Rating(models.Model):
    advisor = models.ForeignKey(Advisor, on_delete=models.CASCADE, related_name='ratings')
    customer = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='given_ratings')
    rating = models.PositiveIntegerField(validators=[MinValueValidator(1), MaxValueValidator(5)])
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        unique_together = ('advisor', 'customer')

    def __str__(self):
        return f"{self.customer.username}'s rating for {self.advisor.name}"

